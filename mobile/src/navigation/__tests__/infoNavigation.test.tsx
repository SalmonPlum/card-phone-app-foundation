import {advance,resetClock,settle,runningClocks} from '../../features/cards/__tests__/helpers/overlayClock';
import {fireEvent,renderRouter,screen} from 'expo-router/testing-library';
import {AppState,StyleSheet} from 'react-native';
import * as native from 'react-native';
import {useLayoutEffect} from 'react';
import Root from '../../app/_layout';
import Tabs from '../../app/(tabs)/_layout';
import Draw from '../../app/(tabs)/index';
import Catalogue from '../../app/(tabs)/catalogue';
import Settings from '../../app/(tabs)/settings';
import History from '../../app/(tabs)/history';
import Details from '../../app/card/[id]';
import Info from '../../app/(tabs)/info';
import {useSession} from '../../session/SessionProvider';
import {historyStorage} from '../../platform/historyStorage';
import type {InfoPage} from '../../info/markdown';
let mockInfo:InfoPage;
jest.mock('../../info',()=>({get configuredInfoPage(){return mockInfo;}}));
jest.mock('expo-router/build/testing-library/mocks',()=>({}));
let mockId=0;
jest.mock('expo-crypto',()=>({randomUUID:()=>`info-${++mockId}`,getRandomValues:(values:Uint32Array)=>{values.fill(0);return values;}}));
let session:ReturnType<typeof useSession>;
function ObservedDraw(){const current=useSession();useLayoutEffect(()=>{session=current;},[current]);return <Draw/>;}
const routes={_layout:Root,'(tabs)/_layout':Tabs,'(tabs)/index':ObservedDraw,'(tabs)/catalogue':Catalogue,'(tabs)/settings':Settings,'(tabs)/history':History,'(tabs)/info':Info,'card/[id]':Details};
const nativeState=AppState.currentState;
beforeEach(()=>{mockInfo=JSON.parse(JSON.stringify(jest.requireActual('../../info/__tests__/fixture').infoFixture));resetClock();mockId=0;AppState.currentState='active';jest.mocked(historyStorage.read).mockResolvedValue(null);});
afterEach(()=>{AppState.currentState=nativeState;jest.mocked(historyStorage.read).mockResolvedValue(null);jest.restoreAllMocks();});
test.each([false,true])('Info appears before Settings with History enabled=%s',async enabled=>{
  jest.mocked(historyStorage.read).mockResolvedValue(JSON.stringify({schemaVersion:1,enabled,sessions:[]}));
  await renderRouter(routes);await settle();
  expect(screen.getAllByRole('tab').map(tab=>tab.props.accessibilityLabel)).toEqual(enabled?['Draw','Catalogue','History','About me','Settings']:['Draw','Catalogue','About me','Settings']);
  await fireEvent.press(screen.getByRole('tab',{name:'About me'}));await settle();
  expect(screen).toHavePathname('/info');expect(screen.getByRole('header',{name:'About me'})).toBeVisible();
  expect(screen.getByRole('tab',{name:'About me'}).props.accessibilityState.selected).toBe(true);
});
test('omitted resource hides the tab and a direct Info link returns to Draw',async()=>{
  mockInfo=null;await renderRouter(routes,{initialUrl:'/info'});await settle();
  expect(screen).toHavePathname('/');expect(screen.getAllByRole('tab')).toHaveLength(3);
  expect(screen.queryByTestId('info-scroll')).toBeNull();
});
test('Info preserves paused drawing across locale, theme and text-size changes',async()=>{
  await renderRouter(routes);await settle();await advance(624);await settle();await advance(144);await settle();
  expect(session.state!.phase).toBe('strip');await advance(200);await settle();
  const paused=session.state!,progress=runningClocks()[0].value;
  await fireEvent.press(screen.getByRole('tab',{name:'About me'}));await settle();
  expect(runningClocks()).toHaveLength(0);expect(session.state).toBe(paused);
  await fireEvent.press(screen.getByRole('tab',{name:'Settings'}));await settle();
  await fireEvent.press(screen.getByRole('radio',{name:'Čeština'}));
  await fireEvent.press(screen.getByRole('radio',{name:'Nebeská půlnoc'}));
  await fireEvent(screen.getByRole('adjustable'),'accessibilityAction',{nativeEvent:{actionName:'increment'}});await settle();
  await fireEvent.press(screen.getByRole('tab',{name:'O mně'}));await settle();
  expect(screen.getByRole('header',{name:'O mně'})).toBeVisible();
  expect(screen.getByText('Klidné místo, kde se můžete zastavit, vytáhnout si kartu a zamyslet se.')).toHaveStyle({fontSize:14.93*1.15});
  expect(session.state).toBe(paused);
  await fireEvent.press(screen.getByRole('tab',{name:'Tahání'}));await settle();
  expect(runningClocks()[0].value).toBeCloseTo(progress);
  await advance(296.001);await settle();
  expect(session.state).toMatchObject({sessionId:paused.sessionId,epoch:paused.epoch+1,phase:'contact'});
});
test('long labels and five tabs consume measured dock height without truncating content',async()=>{
  jest.spyOn(native,'useWindowDimensions').mockReturnValue({width:280,height:480,scale:3,fontScale:2});
  mockInfo!.en.menuLabel='About the author and this app';
  jest.mocked(historyStorage.read).mockResolvedValue(JSON.stringify({schemaVersion:1,enabled:true,sessions:[]}));
  await renderRouter(routes,{initialUrl:'/info'});await settle();
  expect(screen.getAllByRole('tab')).toHaveLength(5);
  for(const tab of screen.getAllByRole('tab'))expect(StyleSheet.flatten(tab.props.style)).toMatchObject({minHeight:48,minWidth:48});
  expect(screen.getByText(mockInfo!.en.menuLabel).props.numberOfLines).toBe(1);
  await fireEvent(screen.getByTestId('bottom-dock'),'layout',{nativeEvent:{layout:{x:0,y:400,width:280,height:174}}});
  expect(StyleSheet.flatten(screen.getByTestId('info-scroll').props.contentContainerStyle).paddingBottom).toBe(198);
});
